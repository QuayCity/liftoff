// Oracle schema diff: reads the schema of the signed-in user from the data dictionary and turns
// differences into Oracle steps, in the same Change / phase shape as the other engines
// (changes.ts), so generate, undo, capture, squash and the drift checks work the same way.
// Objects: tables (columns, identity, virtual columns, defaults), primary keys, unique, check and
// foreign keys, indexes (also on expressions), views, sequences, synonyms, procedures, functions,
// packages, object types, triggers. Counted as "not compared": materialized views, database
// links, temporary tables, grants, comments.
// Names Oracle made up (SYS_C…) differ per database, so those constraints are matched by what
// they say. PL/SQL units end with a `/` line, as SQL*Plus and LiftOff read scripts.

import { compares, type Project } from './config.ts'
import { configError } from './errors.ts'
import { ownTables } from './db.ts'
import { P_DROP, P_DROP_OTHER, P_DROP_TABLES, P_FKS, P_FUNCS, P_KEYS, P_TABLES, P_TRIGGERS, P_TYPES, P_VIEWS, change, sorted, step, withUndo, type Change, type Step } from './changes.ts'
import { lit, quote, type OracleConn } from './oracle.ts'

export type OraColumn = {
  name: string
  data_type: string
  not_null: boolean
  /** the default as written, null when none (identity and virtual columns have none) */
  default: string | null
  /** `GENERATED BY DEFAULT ON NULL AS IDENTITY`, … */
  identity: string | null
  /** a virtual column's expression */
  virtual: string | null
}

export type OraConstraint = {
  name: string
  /** Oracle picked the name (SYS_C…): matched by definition instead */
  system_named: boolean
  /** P, U, C, R */
  kind: string
  /** `PRIMARY KEY (id)`, `CHECK (total >= 0)`, `FOREIGN KEY (c) REFERENCES t (id) ON DELETE CASCADE` */
  def: string
  /** key or foreign-key columns, `A,B`, to find a system-named constraint again */
  cols: string
}

const constraintKey = (c: OraConstraint) => (c.system_named ? `~${c.def}` : c.name)

export type OraTable = {
  columns: OraColumn[]
  constraints: OraConstraint[]
  /** index name -> CREATE INDEX (indexes behind a key are left out) */
  indexes: Map<string, string>
}

/** PL/SQL units and views: their CREATE statement. */
export type UnitKind = 'view' | 'procedure' | 'function' | 'package' | 'package body' | 'type' | 'type body' | 'trigger'

export type Unit = {
  kind: UnitKind
  /** the CREATE OR REPLACE statement, line endings and trailing spaces normalised */
  def: string
  /** triggers: their table */
  table: string | null
}

export type OraSequence = { increment: string; min: string; max: string; cycle: boolean; order: boolean; cache: string }

export type OraModel = {
  tables: Map<string, OraTable>
  /** views and PL/SQL units, by `<kind>:<name>` (a package and its body share a name) */
  units: Map<string, Unit>
  sequences: Map<string, OraSequence>
  /** synonym -> `owner.object` (owner left out when it is this schema) */
  synonyms: Map<string, string>
  not_compared: [string, number][]
}

export const emptyOraModel = (): OraModel => ({ tables: new Map(), units: new Map(), sequences: new Map(), synonyms: new Map(), not_compared: [] })

/* ---------- reading the schema ---------- */

/** A column's type as written in DDL. */
export function typeName(type: string, length: number, charLength: number, charUsed: string | null, precision: number | null, scale: number | null, owner: string | null): string {
  if (owner) return quote(type)
  switch (type) {
    case 'VARCHAR2':
    case 'CHAR':
      return `${type}(${charUsed === 'C' ? `${charLength} CHAR` : length})`
    case 'NVARCHAR2':
    case 'NCHAR':
      return `${type}(${charLength})`
    case 'RAW':
      return `RAW(${length})`
    case 'NUMBER':
      if (precision === null) return scale === 0 ? 'INTEGER' : 'NUMBER'
      return scale ? `NUMBER(${precision},${scale})` : `NUMBER(${precision})`
    case 'FLOAT':
      return precision === 126 || precision === null ? 'FLOAT' : `FLOAT(${precision})`
    default:
      return type
  }
}

const tidy = (s: string) =>
  s
    .replaceAll('\r\n', '\n')
    .split('\n')
    .map((l) => l.trimEnd())
    .join('\n')
    .trim()

/** `"COL" IS NOT NULL`, the check Oracle makes for NOT NULL: the column says it already. */
const notNullCheck = (cond: string) => /^"[^"]+" IS NOT NULL$/.test(cond.trim())

export async function introspect(c: OracleConn, _schemas: string[], excludeTable: string): Promise<OraModel> {
  const m = emptyOraModel()
  const own = ownTables(excludeTable).map(lit).join(', ')
  const s = (v: unknown) => (v ?? '') as string
  const inScope = `SELECT table_name FROM user_tables WHERE table_name NOT IN (${own}) AND table_name NOT LIKE 'BIN$%' AND temporary = 'N' AND nested = 'NO' AND secondary = 'N'
    AND table_name NOT IN (SELECT mview_name FROM user_mviews) AND (iot_type IS NULL OR iot_type = 'IOT')`

  for (const [name] of await c.query(`SELECT table_name FROM user_tables WHERE table_name IN (${inScope}) ORDER BY table_name`)) {
    m.tables.set(s(name), { columns: [], constraints: [], indexes: new Map() })
  }
  const identity = new Map<string, string>()
  for (const [t, col, gen, onNull] of await c.query(
    `SELECT i.table_name, i.column_name, i.generation_type, c.default_on_null FROM user_tab_identity_cols i
     JOIN user_tab_cols c ON c.table_name = i.table_name AND c.column_name = i.column_name`,
  )) {
    identity.set(`${s(t)}.${s(col)}`, `GENERATED ${s(gen)}${s(onNull) === 'YES' ? ' ON NULL' : ''} AS IDENTITY`)
  }
  for (const r of await c.query(
    `SELECT table_name, column_name, data_type, data_length, char_length, char_used, data_precision, data_scale, nullable, data_default, virtual_column, data_type_owner
     FROM user_tab_cols WHERE table_name IN (${inScope}) AND hidden_column = 'NO' ORDER BY table_name, column_id`,
  )) {
    const t = m.tables.get(s(r[0]))
    if (!t) continue
    const id = identity.get(`${s(r[0])}.${s(r[1])}`) ?? null
    const virtual = s(r[10]) === 'YES' ? tidy(s(r[9])) : null
    t.columns.push({
      name: s(r[1]),
      data_type: typeName(s(r[2]), Number(r[3]), Number(r[4]), r[5] as string | null, r[6] as number | null, r[7] as number | null, r[11] as string | null),
      not_null: s(r[8]) === 'N' && !id,
      default: id || virtual || r[9] === null ? null : tidy(s(r[9])) || null,
      identity: id,
      virtual,
    })
  }

  const cols = (table: string) => `(SELECT LISTAGG(cc.column_name, ',') WITHIN GROUP (ORDER BY cc.position) FROM user_cons_columns cc WHERE cc.constraint_name = ${table}.constraint_name)`
  const backing = new Set<string>()
  for (const r of await c.query(
    `SELECT c.table_name, c.constraint_name, c.generated, c.constraint_type, c.search_condition_vc, c.delete_rule, ${cols('c')}, r.table_name, ${cols('r')}, c.index_name
     FROM user_constraints c LEFT JOIN user_constraints r ON r.constraint_name = c.r_constraint_name
     WHERE c.table_name IN (${inScope}) AND c.constraint_type IN ('P', 'U', 'C', 'R')`,
  )) {
    const t = m.tables.get(s(r[0]))
    if (!t) continue
    if (r[9]) backing.add(s(r[9]))
    const kind = s(r[3])
    const list = (v: unknown) => s(v).split(',').map(quote).join(', ')
    let def: string
    if (kind === 'P') def = `PRIMARY KEY (${list(r[6])})`
    else if (kind === 'U') def = `UNIQUE (${list(r[6])})`
    else if (kind === 'C') {
      if (s(r[2]) === 'GENERATED NAME' && notNullCheck(s(r[4]))) continue
      def = `CHECK (${tidy(s(r[4]))})`
    } else {
      const rule = s(r[5]) === 'CASCADE' ? ' ON DELETE CASCADE' : s(r[5]) === 'SET NULL' ? ' ON DELETE SET NULL' : ''
      def = `FOREIGN KEY (${list(r[6])}) REFERENCES ${quote(s(r[7]))} (${list(r[8])})${rule}`
    }
    t.constraints.push({ name: s(r[1]), system_named: s(r[2]) === 'GENERATED NAME', kind, def, cols: s(r[6]) })
  }
  for (const t of m.tables.values()) t.constraints.sort((a, b) => (constraintKey(a) < constraintKey(b) ? -1 : constraintKey(a) > constraintKey(b) ? 1 : 0))

  const exprs = new Map<string, string>()
  for (const [index, pos, expr] of await c.query('SELECT index_name, column_position, column_expression FROM user_ind_expressions')) exprs.set(`${s(index)}.${String(pos)}`, tidy(s(expr)))
  const idx = new Map<string, { table: string; unique: boolean; bitmap: boolean; cols: string[] }>()
  for (const [index, table, uniq, type, col, pos, desc] of await c.query(
    `SELECT i.index_name, i.table_name, i.uniqueness, i.index_type, ic.column_name, ic.column_position, ic.descend
     FROM user_indexes i JOIN user_ind_columns ic ON ic.index_name = i.index_name
     WHERE i.table_name IN (${inScope}) AND i.generated = 'N' AND i.index_type IN ('NORMAL', 'BITMAP', 'FUNCTION-BASED NORMAL', 'FUNCTION-BASED BITMAP')
     ORDER BY i.index_name, ic.column_position`,
  )) {
    if (backing.has(s(index))) continue
    const i = idx.get(s(index)) ?? { table: s(table), unique: s(uniq) === 'UNIQUE', bitmap: s(type).includes('BITMAP'), cols: [] }
    // DESC columns and expressions are hidden columns (SYS_NC…); the expression says which.
    const expr = exprs.get(`${s(index)}.${String(pos)}`)
    const e = expr && s(desc) === 'DESC' && /^"[^"]+"$/.test(expr) ? quote(expr.slice(1, -1)) : expr
    i.cols.push(`${e ?? quote(s(col))}${s(desc) === 'DESC' ? ' DESC' : ''}`)
    idx.set(s(index), i)
  }
  for (const [name, i] of idx) {
    m.tables.get(i.table)?.indexes.set(name, `CREATE ${i.unique ? 'UNIQUE ' : i.bitmap ? 'BITMAP ' : ''}INDEX ${quote(name)} ON ${quote(i.table)} (${i.cols.join(', ')})`)
  }

  for (const [name, text] of await c.query('SELECT view_name, text FROM user_views')) {
    m.units.set(`view:${s(name)}`, { kind: 'view', def: `CREATE OR REPLACE VIEW ${quote(s(name))} AS\n${tidy(s(text))}`, table: null })
  }
  const triggerTable = new Map<string, string>()
  for (const [name, table] of await c.query(`SELECT trigger_name, table_name FROM user_triggers WHERE base_object_type = 'TABLE'`)) triggerTable.set(s(name), s(table))
  const source = new Map<string, string[]>()
  for (const [type, name, text] of await c.query(
    `SELECT type, name, text FROM user_source WHERE type IN ('PROCEDURE', 'FUNCTION', 'PACKAGE', 'PACKAGE BODY', 'TYPE', 'TYPE BODY', 'TRIGGER') AND name NOT LIKE 'SYS_PLSQL_%' ORDER BY type, name, line`,
  )) {
    const k = `${s(type).toLowerCase()}:${s(name)}`
    if (!source.has(k)) source.set(k, [])
    source.get(k)!.push(s(text))
  }
  for (const [k, lines] of source) {
    const kind = k.slice(0, k.indexOf(':')) as UnitKind
    const name = k.slice(k.indexOf(':') + 1)
    // Triggers on anything but this schema's compared tables (views, the schema itself) are left out.
    if (kind === 'trigger' && !m.tables.has(triggerTable.get(name) ?? '')) continue
    m.units.set(k, { kind, def: `CREATE OR REPLACE ${tidy(lines.join(''))}`, table: kind === 'trigger' ? triggerTable.get(name)! : null })
  }

  for (const r of await c.query(`SELECT sequence_name, increment_by, min_value, max_value, cycle_flag, order_flag, cache_size FROM user_sequences WHERE sequence_name NOT LIKE 'ISEQ$$%'`)) {
    m.sequences.set(s(r[0]), { increment: String(r[1]), min: String(r[2]), max: String(r[3]), cycle: s(r[4]) === 'Y', order: s(r[5]) === 'Y', cache: String(r[6]) })
  }
  for (const [name, owner, target] of await c.query('SELECT synonym_name, table_owner, table_name FROM user_synonyms')) {
    m.synonyms.set(s(name), `${s(owner) && s(owner) !== c.schema ? `${quote(s(owner))}.` : ''}${quote(s(target))}`)
  }

  for (const r of await c.query(
    `SELECT 'materialized views', COUNT(*) FROM user_mviews
     UNION ALL SELECT 'database links', COUNT(*) FROM user_db_links
     UNION ALL SELECT 'temporary tables', COUNT(*) FROM user_tables WHERE temporary = 'Y'
     UNION ALL SELECT 'grants', COUNT(*) FROM user_tab_privs_made
     UNION ALL SELECT 'comments', (SELECT COUNT(*) FROM user_tab_comments WHERE comments IS NOT NULL) + (SELECT COUNT(*) FROM user_col_comments WHERE comments IS NOT NULL) FROM dual`,
  )) {
    const n = Number(r[1])
    if (n > 0) m.not_compared.push([s(r[0]), n])
  }
  return m
}

const filterKind: Record<UnitKind, string> = { view: 'view', procedure: 'function', function: 'function', package: 'function', 'package body': 'function', type: 'type', 'type body': 'type', trigger: 'trigger' }

/** Removes what the project's comparison filters exclude; a table takes its triggers along. */
export function applyFilters(m: OraModel, p: Project): void {
  if (!p.filters.length) return
  for (const k of [...m.tables.keys()]) if (!compares(p, 'table', '', k)) m.tables.delete(k)
  for (const [k, u] of [...m.units]) {
    const name = k.slice(k.indexOf(':') + 1)
    if (!compares(p, filterKind[u.kind], '', name) || (u.table && !m.tables.has(u.table))) m.units.delete(k)
  }
  for (const k of [...m.sequences.keys()]) if (!compares(p, 'sequence', '', k)) m.sequences.delete(k)
}

/* ---------- DDL ---------- */

/** A PL/SQL unit ends with a `/` line. */
const block = (sql: string) => `${sql.trimEnd()}\n/`

function colDef(c: OraColumn): string {
  let s = `${quote(c.name)} ${c.data_type}`
  if (c.virtual) return `${s} GENERATED ALWAYS AS (${c.virtual}) VIRTUAL`
  if (c.identity) s += ` ${c.identity}`
  if (c.default !== null) s += ` DEFAULT ${c.default}`
  if (c.not_null) s += ' NOT NULL'
  return s
}

const createTable = (t: string, tb: OraTable) => `CREATE TABLE ${t} (\n${tb.columns.map((c) => `    ${colDef(c)}`).join(',\n')}\n);`

const addConstraint = (t: string, c: OraConstraint) => (c.system_named ? `ALTER TABLE ${t} ADD ${c.def};` : `ALTER TABLE ${t} ADD CONSTRAINT ${quote(c.name)} ${c.def};`)

/** Drops a constraint whose name is only known in the database it runs on. */
function dropConstraint(table: string, c: OraConstraint): string {
  const t = quote(table)
  if (!c.system_named) return `ALTER TABLE ${t} DROP CONSTRAINT ${quote(c.name)};`
  const where =
    c.kind === 'C'
      ? `constraint_type = 'C' AND search_condition_vc = ${lit(c.def.slice('CHECK ('.length, -1))}`
      : `constraint_type = '${c.kind}' AND (SELECT LISTAGG(column_name, ',') WITHIN GROUP (ORDER BY position) FROM user_cons_columns cc WHERE cc.constraint_name = c.constraint_name) = ${lit(c.cols)}`
  return block(
    `DECLARE\n  n VARCHAR2(128);\nBEGIN\n  SELECT MAX(constraint_name) INTO n FROM user_constraints c WHERE table_name = ${lit(table)} AND generated = 'GENERATED NAME' AND ${where};\n` +
      `  IF n IS NOT NULL THEN EXECUTE IMMEDIATE 'ALTER TABLE ${t.replaceAll("'", "''")} DROP CONSTRAINT "' || n || '"'; END IF;\nEND;`,
  )
}

/**
 * The whole table as one readable block, for the side-by-side view and the schema model. The
 * constraints are inside the CREATE TABLE: Oracle commits each statement, so a schema-model file
 * that fails (a foreign key to a table not built yet) must fail as a whole to be tried again.
 */
export function tableDdl(name: string, tb: OraTable): string {
  const t = quote(name)
  const lines = [...tb.columns.map(colDef), ...tb.constraints.map((c) => (c.system_named ? c.def : `CONSTRAINT ${quote(c.name)} ${c.def}`))]
  return [`CREATE TABLE ${t} (\n${lines.map((l) => `    ${l}`).join(',\n')}\n);`, ...[...tb.indexes.values()].map((d) => `${d};`)].join('\n')
}

const sequenceClauses = (s: OraSequence) =>
  `INCREMENT BY ${s.increment} MINVALUE ${s.min} MAXVALUE ${s.max} ${s.cycle ? 'CYCLE' : 'NOCYCLE'} ${s.cache === '0' ? 'NOCACHE' : `CACHE ${s.cache}`} ${s.order ? 'ORDER' : 'NOORDER'}`
/** ponytail: a new sequence starts at its MINVALUE (or MAXVALUE counting down); where an existing one has got to is data, not schema. */
const sequenceDdl = (name: string, s: OraSequence) => `CREATE SEQUENCE ${quote(name)} START WITH ${Number(s.increment) < 0 ? s.max : s.min} ${sequenceClauses(s)};`

const word: Record<UnitKind, string> = { view: 'VIEW', procedure: 'PROCEDURE', function: 'FUNCTION', package: 'PACKAGE', 'package body': 'PACKAGE BODY', type: 'TYPE', 'type body': 'TYPE BODY', trigger: 'TRIGGER' }
const group: Record<UnitKind, string> = {
  view: 'Views', procedure: 'Procedures', function: 'Functions', package: 'Packages', 'package body': 'Packages', type: 'Types', 'type body': 'Types', trigger: 'Triggers',
}
/** Types first (tables may use them), then functions and package specs, views, then the units that may use views. */
const unitPhase: Record<UnitKind, [number, number]> = {
  type: [P_TYPES, 0], function: [P_FUNCS, 0], package: [P_FUNCS, 1], view: [P_VIEWS, 0], procedure: [P_TRIGGERS, 0], 'package body': [P_TRIGGERS, 1], 'type body': [P_TRIGGERS, 1], trigger: [P_TRIGGERS, 2],
}
const unitSql = (u: Unit) => (u.kind === 'view' ? `${u.def};` : block(u.def))

/* ---------- compare ---------- */

/** Changes that turn `target` into `source`, each with the reverse steps for an undo script. */
export function diff(source: OraModel, target: OraModel): Change[] {
  return withUndo(compare(source, target), compare(target, source))
}

/** Everything in `m` as changes against an empty schema (capture, squash). */
export const createAll = (m: OraModel) => compare(m, emptyOraModel())

const same = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b)

export function compare(source: OraModel, target: OraModel): Change[] {
  const out: Change[] = []

  for (const [name, s] of sorted(source.sequences)) {
    const old = target.sequences.get(name)
    if (!old) out.push(change('sequence', 'Sequences', name, 'added', false, [step(P_TYPES, sequenceDdl(name, s))], null, sequenceDdl(name, s)))
    else if (!same(old, s)) out.push(change('sequence', 'Sequences', name, 'changed', false, [step(P_TYPES, `ALTER SEQUENCE ${quote(name)} ${sequenceClauses(s)};`)], sequenceDdl(name, old), sequenceDdl(name, s)))
  }
  for (const [name, s] of sorted(target.sequences)) {
    if (!source.sequences.has(name)) out.push(change('sequence', 'Sequences', name, 'removed', true, [step(P_DROP_OTHER, `DROP SEQUENCE ${quote(name)};`)], sequenceDdl(name, s), null))
  }

  for (const [name, nw] of sorted(source.tables)) {
    const t = quote(name)
    const old = target.tables.get(name)
    const steps: Step[] = []
    let destructive = false
    if (!old) steps.push(step(P_TABLES, createTable(t, nw)))
    else {
      for (const c of nw.columns) {
        const o = old.columns.find((o) => o.name === c.name)
        if (!o) steps.push(step(P_TABLES, `ALTER TABLE ${t} ADD (${colDef(c)});`))
        else if (!same(o, c)) destructive = alterColumn(t, o, c, steps) || destructive
      }
      for (const o of old.columns) {
        if (nw.columns.some((c) => c.name === o.name)) continue
        destructive = true
        steps.push(step(P_TABLES, `ALTER TABLE ${t} DROP COLUMN ${quote(o.name)};`, 1))
      }
    }
    const oldT: OraTable = old ?? { columns: [], constraints: [], indexes: new Map() }
    const sameCon = (a: OraConstraint, b: OraConstraint) => constraintKey(a) === constraintKey(b) && a.def === b.def
    // Foreign keys go first: a key they point at cannot be dropped before them.
    for (const o of oldT.constraints) if (!nw.constraints.some((c) => sameCon(c, o))) steps.push(step(P_DROP, dropConstraint(name, o), o.kind === 'R' ? 0 : 1))
    for (const c of nw.constraints) if (!oldT.constraints.some((o) => sameCon(o, c))) steps.push(step(c.kind === 'R' ? P_FKS : P_KEYS, addConstraint(t, c)))
    for (const [iname, odef] of sorted(oldT.indexes)) if (nw.indexes.get(iname) !== odef) steps.push(step(P_DROP, `DROP INDEX ${quote(iname)};`, 2))
    for (const [iname, def] of sorted(nw.indexes)) if (oldT.indexes.get(iname) !== def) steps.push(step(P_KEYS, `${def};`))
    if (steps.length) out.push(change('table', 'Tables', name, old ? 'changed' : 'added', destructive, steps, old ? tableDdl(name, old) : null, tableDdl(name, nw)))
  }
  for (const [name, old] of sorted(target.tables)) {
    if (source.tables.has(name)) continue
    // Its own foreign keys go with it (CASCADE CONSTRAINTS), so tables dropped together drop in any order.
    out.push(change('table', 'Tables', name, 'removed', true, [step(P_DROP_TABLES, `DROP TABLE ${quote(name)} CASCADE CONSTRAINTS PURGE;`)], tableDdl(name, old), null))
  }

  for (const [k, u] of sorted(source.units)) {
    const name = k.slice(k.indexOf(':') + 1)
    const old = target.units.get(k)
    if (old?.def === u.def) continue
    const [phase, order] = unitPhase[u.kind]
    out.push(change(u.kind.replace(' ', '-'), group[u.kind], name, old ? 'changed' : 'added', false, [step(phase, unitSql(u), order)], old?.def ?? null, u.def))
  }
  for (const [k, u] of sorted(target.units)) {
    if (source.units.has(k)) continue
    const name = k.slice(k.indexOf(':') + 1)
    // Dropping a table drops its triggers; dropping a package or type drops its body.
    if (u.table && !source.tables.has(u.table)) continue
    if (u.kind.endsWith(' body') && !source.units.has(`${u.kind.replace(' body', '')}:${name}`)) continue
    const phase = u.kind === 'function' || u.kind === 'type' || u.kind === 'package' ? P_DROP_OTHER : P_DROP
    out.push(change(u.kind.replace(' ', '-'), group[u.kind], name, 'removed', false, [step(phase, `DROP ${word[u.kind]} ${quote(name)}${u.kind === 'type' ? ' FORCE' : ''};`)], u.def, null))
  }

  for (const [name, to] of sorted(source.synonyms)) {
    const old = target.synonyms.get(name)
    const ddl = `CREATE OR REPLACE SYNONYM ${quote(name)} FOR ${to};`
    if (old !== to) out.push(change('synonym', 'Synonyms', name, old ? 'changed' : 'added', false, [step(P_VIEWS, ddl, 1)], old ? `CREATE OR REPLACE SYNONYM ${quote(name)} FOR ${old};` : null, ddl))
  }
  for (const [name, to] of sorted(target.synonyms)) {
    if (!source.synonyms.has(name)) out.push(change('synonym', 'Synonyms', name, 'removed', false, [step(P_DROP, `DROP SYNONYM ${quote(name)};`)], `CREATE OR REPLACE SYNONYM ${quote(name)} FOR ${to};`, null))
  }
  return out
}

/** True when the change may lose data. */
function alterColumn(t: string, o: OraColumn, c: OraColumn, steps: Step[]): boolean {
  const col = quote(c.name)
  if (o.identity !== c.identity || o.virtual !== null || c.virtual !== null) {
    if (o.virtual !== null && c.virtual !== null) {
      // A virtual column is replaced: drop and add.
      steps.push(step(P_TABLES, `ALTER TABLE ${t} DROP COLUMN ${col};`), step(P_TABLES, `ALTER TABLE ${t} ADD (${colDef(c)});`))
      return false
    }
    steps.push(step(P_TABLES, `-- ${t}.${col}: identity or virtual-column changes need a new column and a copy; write this change by hand.`))
    return true
  }
  // MODIFY names only what changes: NOT NULL on a column that is already NOT NULL is an error.
  const parts: string[] = []
  if (o.data_type !== c.data_type) parts.push(c.data_type)
  if (o.default !== c.default) parts.push(`DEFAULT ${c.default ?? 'NULL'}`)
  if (o.not_null !== c.not_null) parts.push(c.not_null ? 'NOT NULL' : 'NULL')
  if (parts.length) steps.push(step(P_TABLES, `ALTER TABLE ${t} MODIFY (${col} ${parts.join(' ')});`))
  return o.data_type !== c.data_type
}

/** The schema model: one file per object, `<type>/<name>.sql`. */
export function files(m: OraModel): Map<string, string> {
  const f = (s: string) => quote(s).replace(/^"|"$/g, '').replace(/[/\\:*?"<>|]/g, '_')
  const out = new Map<string, string>()
  const put = (p: string, body: string) => {
    if (out.has(p)) throw configError(`two objects would share the schema-model file ${p}; rename one of them`)
    out.set(p, `${body.trimEnd()}\n`)
  }
  for (const [name, t] of sorted(m.tables)) put(`tables/${f(name)}.sql`, tableDdl(name, t))
  const dir: Record<UnitKind, string> = { view: 'views', procedure: 'procedures', function: 'functions', package: 'packages', 'package body': 'packages', type: 'types', 'type body': 'types', trigger: 'triggers' }
  for (const [k, u] of sorted(m.units)) {
    const name = k.slice(k.indexOf(':') + 1)
    put(`${dir[u.kind]}/${f(name)}${u.kind.endsWith(' body') ? '.body' : ''}.sql`, unitSql(u))
  }
  for (const [name, s] of sorted(m.sequences)) put(`sequences/${f(name)}.sql`, sequenceDdl(name, s))
  for (const [name, to] of sorted(m.synonyms)) put(`synonyms/${f(name)}.sql`, `CREATE OR REPLACE SYNONYM ${quote(name)} FOR ${to};`)
  return out
}
