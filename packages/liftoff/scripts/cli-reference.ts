// Writes docs/guide/cli-reference.md from the program's own help, so the reference never drifts
// from the code. Run from packages/liftoff: node scripts/cli-reference.ts
import { execFileSync } from 'node:child_process'
import * as fs from 'node:fs'

const help = (...args: string[]) => execFileSync(process.execPath, ['src/cli/main.ts', ...args, '--help'], { encoding: 'utf8' })

const GROUPS: [string, string[]][] = [
  ['Projects and settings', ['init', 'settings', 'project', 'test-connection', 'create-scratch']],
  ['Writing migrations', ['diff', 'generate', 'add', 'capture', 'model']],
  ['Deploying', ['info', 'migrate', 'check', 'validate', 'repair', 'undo', 'mark-applied', 'baseline', 'clean']],
  ['Existing databases and baselines', ['adopt', 'squash', 'rebaseline']],
  ['Compare', ['compare', 'snapshot', 'data-compare']],
  ['Teams and pipelines', ['renumber', 'ci']],
  ['Flyway', ['import-flyway-history']],
]

const listed = help().split('Commands:')[1].split('Options:')[0].trim().split('\n').map((l) => l.trim().split(/\s+/)[0])
const grouped = GROUPS.flatMap(([, c]) => c)
const missing = listed.filter((c) => !grouped.includes(c))
if (missing.length) throw new Error(`add these commands to a group: ${missing.join(', ')}`)

/** The options every command takes are listed once, at the top. */
const GLOBAL = /^\s+(-C, --project-dir|-e, --environment|--output-type|--placeholder|-h, --help|-V, --version)\b/

let md = `# Command reference

Every command and option, as \`liftoff <command> --help\` prints them. This page is generated by
\`node scripts/cli-reference.ts\` in \`packages/liftoff\`; do not edit it by hand.

## Options every command takes

| option | what |
| --- | --- |
| \`-C, --project-dir <DIR>\` | the project folder, which holds \`liftoff.toml\` (default: the current folder) |
| \`-e, --environment <NAME>\` | the environment to work on |
| \`--output-type <TYPE>\` | \`text\` (default) or \`json\`: one JSON object on stdout, progress on stderr |
| \`--placeholder <NAME=VALUE>\` | a value for \`\${NAME}\` in the scripts, for this run; repeatable |
| \`-h, --help\` | the command's help |
| \`-V, --version\` | the program's version |

Flyway-style options (\`-url=…\`, \`-user=…\`, \`-locations=filesystem:…\`) are accepted too; see
[Moving from Flyway](flyway.md#flyway-style-arguments). Exit codes are listed in
[Deploying](deploying.md#exit-codes).

## Commands

`
for (const [title, cmds] of GROUPS) md += `- **${title}:** ${cmds.map((c) => `[\`${c}\`](#${c})`).join(', ')}\n`
for (const [title, cmds] of GROUPS) {
  md += `\n## ${title}\n`
  for (const c of cmds) {
    const text = help(c).replaceAll('\r', '')
    const [summary, ...rest] = text.split('\n\n')
    const body = rest.join('\n\n').split('\n').filter((l) => !GLOBAL.test(l)).join('\n').replace(/\nOptions:\n*$/, '').trimEnd()
    md += `\n### ${c}\n\n${summary.trim()}\n\n\`\`\`\n${body}\n\`\`\`\n`
  }
}
fs.writeFileSync('../../docs/guide/cli-reference.md', md)
console.log(`wrote docs/guide/cli-reference.md: ${listed.length} commands`)
