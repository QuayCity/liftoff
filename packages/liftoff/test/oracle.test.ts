/** e.g. oracle://system:liftoff@localhost:51621/FREEPDB1: a user that may create users. */
const admin = process.env.LIFTOFF_TEST_ORACLE
const url = admin ? admin.replace(/\/\/[^@/]*@/, '//') : ''
const PASSWORD = 'Liftoff_2026'

async function freshUsers(...users: string[]) {
  const a = await OracleConn.open('admin', { url: admin!, role: 'prod', allow_clean: false, placeholders: {} })
  for (const u of users) {
    await a.batch(`BEGIN EXECUTE IMMEDIATE 'DROP USER ${u} CASCADE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -1918 THEN RAISE; END IF; END;
/
CREATE USER ${u} IDENTIFIED BY ${PASSWORD} QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE, CREATE TRIGGER, CREATE TYPE, CREATE SYNONYM TO ${u};`)
  }
  await a.close()
}

const env = (user: string) => ({ user, password: PASSWORD })

test('the Oracle sample project runs and undoes', { skip: !admin && 'set LIFTOFF_TEST_ORACLE' }, async () => {
  const { createSample } = await import('../src/core/sample.ts')
  const { saveEnvironment } = await import('../src/core/config.ts')
  const fs = await import('node:fs')
  const os = await import('node:os')
  const path = await import('node:path')
  await freshUsers('shop_sample')
  const root = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'lo-orasample-')), 'sample')
  createSample(root, 'oracle')
  saveEnvironment(root, 'test', { url, ...env('shop_sample'), role: 'test', allow_clean: false, placeholders: {} }, true, false)
  const cfg = Config.load(root)
  const r = await runner.migrate(cfg, 'test')
  assert.deepEqual(r.applied.map((a) => a.script), ['V0001__customers.sql', 'V0002__orders.sql', 'V0003__orders_by_customer.sql', 'R__customer_totals.sql'])
  await runner.undo(cfg, 'test')
  assert.equal((await runner.info(cfg, 'test')).find((i) => i.script === 'V0003__orders_by_customer.sql')?.state, 'pending')
})

test('the runner on Oracle', { skip: !admin && 'set LIFTOFF_TEST_ORACLE' }, async () => {
  await freshUsers('shop_test', 'shop_dev')
  const p = project('oracle', [
    ['test', url, 'test', env('shop_test')],
    ['dev', url, 'dev', { ...env('shop_dev'), allow_clean: true }],
  ])
  const cfg = p.cfg()
  assert.deepEqual(cfg.project.schemas, [], "Oracle manages the signed-in user's schema")

  // DDL, PL/SQL ending with /, a q-quoted string, and data in a transaction of its own.
  p.write('V1__start.sql', 'create table orders (id number generated by default as identity primary key, note varchar2(100) default \'-\' not null);\n')
  p.write('V2__routines.sql', "create or replace procedure add_order(n varchar2) is\nbegin\n  insert into orders (note) values (n);\nend;\n/\ninsert into orders (note) values (q'[it's; fine]');\n")
  p.write('R__view.sql', 'create or replace view order_notes as select id, note from orders;\n')
  p.write('V3__more.sql', "insert into orders (note) values ('three');\n")
  p.write('U3__more.sql', "delete from orders where note = 'three';\n")
  const r = await runner.migrate(cfg, 'test')
  assert.deepEqual(r.applied.map((a) => a.script), ['V1__start.sql', 'V2__routines.sql', 'V3__more.sql', 'R__view.sql'])
  assert.deepEqual(r.applied.map((a) => a.transactional), [false, false, true, false])
  assert.ok(await succeeds(cfg, 'test', "begin add_order('x'); end;\n/"))

  // A dry run: the runner's transaction and the history row; nothing runs.
  p.write('V4__dry.sql', "insert into orders (note) values ('dry');\n")
  const dry = (await runner.migrate(cfg, 'test', { dryRun: true })).dry_run_sql!
  assert.ok(dry.includes('SET TRANSACTION READ WRITE;') && dry.includes('INSERT INTO "liftoff_schema_history"'), dry)
  p.remove('V4__dry.sql')

  // Data only: one transaction, rolled back on failure, nothing recorded.
  p.write('V4__bad.sql', "insert into orders (note) values ('kept?');\ninsert into no_such_table values (1);\n")
  await assert.rejects(runner.migrate(cfg, 'test'), (e: unknown) => e instanceof MigrationError && /ORA-00942/.test(e.message))
  assert.equal((await runner.info(cfg, 'test')).find((i) => i.script === 'V4__bad.sql')?.state, 'pending')
  assert.ok(await succeeds(cfg, 'test', "declare n number; begin select count(*) into n from orders where note = 'kept?'; if n > 0 then raise_application_error(-20000, 'kept'); end if; end;\n/"))
  p.remove('V4__bad.sql')

  // PL/SQL that does not compile fails with its errors; repair clears the failure.
  p.write('V4__broken.sql', 'create or replace procedure broken is begin no_such_thing; end;\n/\n')
  await assert.rejects(runner.migrate(cfg, 'test'), /PLS-00201/)
  assert.equal((await runner.info(cfg, 'test')).find((i) => i.script === 'V4__broken.sql')?.state, 'failed')
  assert.deepEqual((await runner.repair(cfg, 'test')).removed_failed, ['V4__broken.sql'])
  p.remove('V4__broken.sql')
  await sql(cfg, 'test', 'drop procedure broken')

  // Undo, clean, and a schema with objects but no history.
  await runner.undo(cfg, 'test')
  assert.equal((await runner.info(cfg, 'test')).find((i) => i.script === 'V3__more.sql')?.state, 'pending')
  await runner.migrate(cfg, 'dev')
  await runner.clean(cfg, 'dev')
  assert.ok(!(await succeeds(cfg, 'dev', 'select 1 from orders')), 'clean drops everything')
  await sql(cfg, 'dev', 'create table stray (id number)')
  await assert.rejects(runner.migrate(cfg, 'dev'), /baseline|objects/i)
})

test('data compare on Oracle: 8,000 rows, types, keys, order, and a script that fixes it', { skip: !admin && 'set LIFTOFF_TEST_ORACLE' }, async () => {
  await freshUsers('dc_a', 'dc_b')
  const p = project('oracle', [
    ['a', url, 'dev', env('dc_a')],
    ['b', url, 'test', env('dc_b')],
  ])
  const cfg = p.cfg()
  for (const e of ['a', 'b']) {
    await sql(cfg, e, `create table customers (
        id number(10) primary key, email varchar2(100) not null, note varchar2(100), amount number(12, 2), seen timestamp(3),
        data raw(16), born date, ratio binary_double, notes clob);
      create table orders (id number(10) primary key, customer_id number(10) not null references customers (id));
      create table line_items (order_id number(10) not null references orders (id), line number(3) not null, item varchar2(50), primary key (order_id, line));
      create table nokey (a number, b varchar2(10));
      insert into customers (id, email, note, amount, seen, data, born, ratio, notes)
        select level, 'c' || level || '@example.com', case when mod(level, 7) = 0 then null else 'note ' || level end, level * 1.25,
               timestamp '2026-01-01 00:00:00' + numtodsinterval(level, 'MINUTE'), hextoraw(lpad(to_char(level, 'FMXXXXXXXX'), 8, '0')),
               date '2000-01-01' + level, level / 3, 'long text ' || level
          from dual connect by level <= 8000;
      insert into orders select level, level from dual connect by level <= 100;
      insert into line_items select o.id, l.n, 'item ' || o.id || '-' || l.n from orders o, (select level n from dual connect by level <= 3) l;
      insert into nokey values (1, 'x'); insert into nokey values (2, 'y'); insert into nokey values (3, null);
      commit;`)
  }
  await sql(cfg, 'a', `insert into nokey values (2, 'y');
    insert into customers (id, email) values (8001, 'new@example.com'); insert into orders values (101, 8001);
    insert into line_items values (101, 1, 'new line'); insert into line_items values (101, 2, q'[O'Brien]');
    commit;`)
  await sql(cfg, 'b', `update nokey set b = 'z' where a = 3; insert into nokey values (4, 'w');
    update customers set amount = 12.51 where id = 10;
    update customers set data = hextoraw('00') where id = 4000;
    update customers set born = born + 1 where id = 5000;
    update customers set ratio = 0.5 where id = 6000;
    update customers set notes = 'only a LOB differs' where id = 7000;
    delete from line_items where order_id = 5 and line = 2;
    insert into customers (id, email) values (9000, 'only-b@example.com'); insert into orders values (200, 9000); insert into line_items values (200, 1, 'stale');
    commit;`)

  const { DataSession } = await import('../src/core/datacompare.ts')
  const { parseSide } = await import('../src/core/compare.ts')
  const logged: string[] = []
  const s = await DataSession.open(cfg, parseSide('a'), parseSide('b'), undefined, (_l, m) => logged.push(m))
  try {
    const t = Object.fromEntries(s.result.tables.map((x) => [x.table, x]))
    assert.ok(logged.some((m) => m.startsWith('CUSTOMERS: ') && m.includes('buckets differ')), `the bucket path ran: ${logged.join(' | ')}`)
    // The LOB is not compared: 4 differences, not 5.
    assert.deepEqual([t.CUSTOMERS.only_in_source, t.CUSTOMERS.only_in_target, t.CUSTOMERS.different], [1, 1, 4], JSON.stringify(t.CUSTOMERS))
    assert.deepEqual([t.ORDERS.only_in_source, t.ORDERS.only_in_target], [1, 1])
    assert.deepEqual([t.LINE_ITEMS.only_in_source, t.LINE_ITEMS.only_in_target, t.LINE_ITEMS.key], [3, 1, ['ORDER_ID', 'LINE']])
    assert.deepEqual([t.NOKEY.only_in_source, t.NOKEY.only_in_target, t.NOKEY.whole_rows], [2, 2, true])
    assert.ok(!('liftoff_schema_history' in t))
    const page = await s.page('CUSTOMERS', 'different', 0, 10)
    assert.ok(!page.columns.includes('NOTES'), 'LOB columns are not compared')

    let script = ''
    for await (const chunk of s.script()) script += chunk
    assert.ok(script.search(/DELETE FROM line_items/) < script.search(/DELETE FROM orders/), 'child rows are deleted first')
    assert.ok(script.search(/INSERT INTO customers/) < script.search(/INSERT INTO line_items/), 'parent rows are inserted first')
    assert.match(script, /SET amount = TO_NUMBER\('12\.5'\) WHERE id = TO_NUMBER\('10'\)/)
    assert.match(script, /'O''Brien'/)
    await s.apply()
  } finally {
    await s.close()
  }
  const again = await DataSession.open(cfg, parseSide('a'), parseSide('b'))
  try {
    for (const r of again.result.tables.filter((x) => !x.skipped)) assert.deepEqual([r.table, r.only_in_source, r.only_in_target, r.different], [r.table, 0, 0, 0])
  } finally {
    await again.close()
  }
})

test('the diff loop on Oracle', { skip: !admin && 'set LIFTOFF_TEST_ORACLE' }, async () => {
  await freshUsers('shop_dev', 'shop_test', 'shop_scratch')
  const p = project('oracle', [
    ['dev', url, 'dev', env('shop_dev')],
    ['test', url, 'test', env('shop_test')],
    ['scratch', url, 'scratch', { ...env('shop_scratch'), allow_clean: true }],
  ])
  const cfg = Config.load(p.dir)
  const ids = (changes: { id: string }[]) => changes.map((c) => c.id).sort()

  // 1. The same scripts in two schemas compare equal, whatever names Oracle made up.
  p.write(
    'V1__start.sql',
    `create table customers (id number(10) primary key, email varchar2(200 char) not null unique);
create table orders (
  id number generated always as identity primary key,
  customer_id number(10) not null references customers (id),
  note varchar2(100) default 'none' not null,
  total number(10,2) check (total >= 0),
  doubled number generated always as (total * 2) virtual
);
create index ix_orders_note on orders (note);
create sequence invoice_no start with 1000 increment by 1 nocache;
create or replace view order_notes as select id, note from orders;
create or replace procedure add_order(n varchar2) is
begin
  insert into orders (customer_id, note) values (1, n);
end;
/
create or replace function order_count return number is
  n number;
begin
  select count(*) into n from orders;
  return n;
end;
/
`,
  )
  for (const e of ['dev', 'test']) await runner.migrate(cfg, e)
  assert.deepEqual(ids((await diff.devVsMigrations(cfg, undefined, undefined)).changes), [])

  // 2. Change dev by hand in every way the diff knows.
  for (const s of [
    'create table invoices (id number primary key, order_id number constraint fk_invoice_order references orders (id) on delete cascade)',
    "alter table orders add (status varchar2(20) default 'new' not null)",
    'alter table orders modify (note varchar2(200))',
    'create index ix_orders_status on orders (status, total desc)',
    'drop index ix_orders_note',
    'alter sequence invoice_no increment by 10',
    'create or replace view order_notes as select id, note, status from orders',
    "create or replace procedure add_order(n varchar2) is\nbegin\n  insert into orders (customer_id, note, status) values (1, n, 'new');\nend;\n/",
    'create or replace package shop_api as\n  function version return number;\nend shop_api;\n/',
    'create or replace package body shop_api as\n  function version return number is begin return 2; end;\nend shop_api;\n/',
    "create or replace trigger orders_touch before update on orders for each row\nbegin\n  :new.note := trim(:new.note);\nend;\n/",
    'create synonym bills for invoices',
    'drop function order_count',
  ]) {
    await sql(cfg, 'dev', s)
  }
  let cmp = await diff.devVsMigrations(cfg, undefined, undefined)
  assert.deepEqual(ids(cmp.changes), [
    'function:ORDER_COUNT', 'package-body:SHOP_API', 'package:SHOP_API', 'procedure:ADD_ORDER', 'sequence:INVOICE_NO', 'synonym:BILLS',
    'table:INVOICES', 'table:ORDERS', 'trigger:ORDERS_TOUCH', 'view:ORDER_NOTES',
  ])
  assert.ok(cmp.changes.find((c) => c.id === 'table:ORDERS')!.destructive, 'a column type change may lose data')

  // 3. Generate with undo, run it on test, record it on dev: everything matches again.
  const g = diff.generate(cfg, cmp.changes, 'invoices and status', true)
  diff.save(cfg, g.file_name, g.sql)
  diff.save(cfg, g.undo!.file_name, g.undo!.sql)
  await runner.migrate(cfg, 'test')
  await runner.markApplied(cfg, 'dev', g.file_name)
  cmp = await diff.devVsMigrations(cfg, undefined, undefined)
  assert.deepEqual(ids(cmp.changes), [], g.sql)

  // 4. No drift on test; the undo script takes test back and there is still no drift.
  let drift = (await checks.check(cfg, 'test', undefined, { drift: true })).drift!
  assert.deepEqual(ids(drift), [])
  await runner.undo(cfg, 'test')
  drift = (await checks.check(cfg, 'test', undefined, { drift: true })).drift!
  assert.deepEqual(ids(drift), [], `${g.undo!.sql}\n${drift.map((d) => `${d.before}\n---\n${d.after}`).join('\n')}`)

  // 5. Drift is seen: a hand-made index on test.
  await sql(cfg, 'test', 'create index ix_by_hand on orders (total)')
  assert.deepEqual(ids((await checks.check(cfg, 'test', undefined, { drift: true })).drift!), ['table:ORDERS'])

  // 6. Capture and squash build the whole schema from nothing, checked by a rebuild.
  const cap = await diff.capture(cfg, 'dev', 'existing schema', false)
  assert.ok(cap.sql.includes('CREATE TABLE customers') && cap.sql.includes('\n/\n'), cap.sql)
  const sq = await diff.squash(cfg, undefined, 'start', undefined, false)
  assert.ok(sq.path && sq.generated.file_name.startsWith('B'))

  // 7. The schema model writes one file per object, and builds again.
  const changes = await model.status(cfg, undefined)
  const paths = changes.map((f) => f.path)
  for (const f of ['tables/orders.sql', 'views/order_notes.sql', 'procedures/add_order.sql', 'packages/shop_api.sql', 'packages/shop_api.body.sql', 'triggers/orders_touch.sql', 'sequences/invoice_no.sql']) {
    assert.ok(paths.includes(f), `${f} in ${paths}`)
  }
  model.save(cfg, changes)
  assert.equal(await model.check(cfg, undefined), paths.length)
  assert.deepEqual(ids((await model.versusMigrations(cfg, undefined)).changes), [])
})
